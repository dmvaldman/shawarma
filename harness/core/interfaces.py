"""Portability contracts. Implementations arrive at their roadmap milestones."""

from collections.abc import AsyncIterator, Sequence
from decimal import Decimal
from typing import Any, Protocol
from uuid import UUID

from harness.core.types import AgentIdentity, ModelResponse, Notification, Post, ToolSpec, Usage


class MattermostAdapter(Protocol):
    async def post_channel(self, channel_id: str, text: str, root_post_id: str = "") -> Post: ...
    async def read_channel(self, channel_id: str, limit: int = 50) -> list[Post]: ...
    async def create_channel(self, team_id: str, name: str, display_name: str) -> str: ...
    async def send_dm(self, recipient_id: str, text: str) -> Post: ...
    async def get_thread(self, root_post_id: str) -> list[Post]: ...
    async def add_reaction(self, post_id: str, emoji_name: str) -> None: ...
    async def remove_reaction(self, post_id: str, emoji_name: str) -> None: ...
    async def search_messages(self, team_id: str, query: str) -> list[Post]: ...
    def events(self) -> AsyncIterator[dict[str, Any]]: ...


class AgentRepository(Protocol):
    async def create(self, identity: AgentIdentity) -> None: ...
    async def get(self, agent_id: UUID) -> AgentIdentity: ...
    async def list_agents(self, workspace_id: UUID) -> Sequence[AgentIdentity]: ...
    async def set_state(self, agent_id: UUID, state: str) -> None: ...


class NotificationRepository(Protocol):
    async def enqueue(self, notification: Notification) -> bool: ...
    async def reserve(self, agent_id: UUID, limit: int) -> Sequence[Notification]: ...
    async def acknowledge(self, notification_ids: Sequence[UUID]) -> None: ...
    async def release(self, notification_ids: Sequence[UUID]) -> None: ...
    async def unread_count(self, agent_id: UUID) -> int: ...


class ModelProvider(Protocol):
    async def generate(
        self,
        messages: Sequence[dict[str, Any]],
        tools: Sequence[ToolSpec],
        model_id: str,
        max_tokens: int,
        timeout: float,  # noqa: ASYNC109 - adapter contract owns the transport deadline
    ) -> ModelResponse: ...


class ToolExecutor(Protocol):
    async def execute(
        self,
        agent_id: UUID,
        tool: ToolSpec,
        arguments: dict[str, Any],
        timeout: float,  # noqa: ASYNC109 - adapter contract owns the transport deadline
    ) -> dict[str, Any]: ...


class AgentScheduler(Protocol):
    async def wake(self, agent_id: UUID) -> None: ...
    async def stop(self, workspace_id: UUID) -> None: ...


class UsageMeter(Protocol):
    async def reserve(self, agent_id: UUID, amount_usd: Decimal) -> UUID: ...
    async def record(self, reservation_id: UUID, usage: Usage) -> None: ...
